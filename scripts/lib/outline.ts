import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

export interface OutlineTopic {
  label?: string
  text?: string
  items: string[]
}

export interface OutlineSection {
  number: string
  title: string
  summary?: string
  topics: OutlineTopic[]
}

export interface OutlinePart {
  part: number
  title: string
  /** Bullets of Parts that have no numbered sections (Parts 26 to 28). */
  topics: OutlineTopic[]
  sections: OutlineSection[]
}

export const OUTLINE_DOC = resolve(import.meta.dirname, '../../docs/MASTER_OUTLINE.md')
export const OUTLINE_GENERATED = resolve(import.meta.dirname, '../../src/content/registry/outline.generated.ts')

const PART_LINE = /^### Part (\d+): (.+)$/
const SECTION_LINE = /^- \*\*(\d+\.\d+) (.+?)[:.]\*\*\s*(.*)$/
const BULLET_LINE = /^( *)- (.+)$/
const BOLD_LEAD = /^\*\*(.+?)\*\*\s*(.*)$/

/** Split "**Label:** text" into its parts; plain bullets have no label. */
function parseBullet(content: string): { label?: string; text?: string } {
  const bold = BOLD_LEAD.exec(content)
  if (!bold) return { text: content.trim() }
  const label = bold[1].replace(/[:.]$/, '').trim()
  const text = bold[2].trim()
  return text ? { label, text } : { label }
}

/** "**Limiters:** peak, brickwall" becomes "Limiters: peak, brickwall". */
function flatten(content: string): string {
  const { label, text } = parseBullet(content)
  return label ? (text ? `${label}: ${text}` : label) : (text ?? '')
}

export function parseOutline(markdown: string): OutlinePart[] {
  const parts: OutlinePart[] = []
  let part: OutlinePart | undefined
  let section: OutlineSection | undefined
  let topic: OutlineTopic | undefined

  for (const line of markdown.split(/\r?\n/)) {
    if (line.startsWith('## ')) {
      part = section = topic = undefined
      continue
    }
    const partMatch = PART_LINE.exec(line)
    if (partMatch) {
      part = { part: Number(partMatch[1]), title: partMatch[2].trim(), topics: [], sections: [] }
      parts.push(part)
      section = topic = undefined
      continue
    }
    if (!part) continue

    const sectionMatch = SECTION_LINE.exec(line)
    if (sectionMatch) {
      const number = sectionMatch[1]
      if (!number.startsWith(`${part.part}.`)) {
        throw new Error(`Section ${number} appears under Part ${part.part} in MASTER_OUTLINE.md`)
      }
      section = { number, title: sectionMatch[2].trim(), topics: [] }
      if (sectionMatch[3].trim()) section.summary = sectionMatch[3].trim()
      part.sections.push(section)
      topic = undefined
      continue
    }

    const bullet = BULLET_LINE.exec(line)
    if (!bullet) continue
    const depth = bullet[1].length
    const content = bullet[2]

    if (depth === 0) {
      // An unnumbered top-level bullet belongs to the Part itself.
      section = undefined
      topic = { ...parseBullet(content), items: [] }
      part.topics.push(topic)
    } else if (depth === 2 && section) {
      topic = { ...parseBullet(content), items: [] }
      section.topics.push(topic)
    } else if (topic) {
      topic.items.push(flatten(content))
    }
  }
  return parts
}

export function readOutline(): OutlinePart[] {
  return parseOutline(readFileSync(OUTLINE_DOC, 'utf8'))
}

export function renderGenerated(parts: OutlinePart[]): string {
  return [
    '// Generated by scripts/sync-outline.ts from docs/MASTER_OUTLINE.md. Do not edit by hand;',
    '// edit the outline and run `npm run sync:outline`.',
    '',
    'export interface OutlineTopic {',
    '  label?: string',
    '  text?: string',
    '  items: string[]',
    '}',
    '',
    'export interface OutlineSection {',
    '  number: string',
    '  title: string',
    '  summary?: string',
    '  topics: OutlineTopic[]',
    '}',
    '',
    'export interface OutlinePart {',
    '  part: number',
    '  title: string',
    '  /** Bullets of Parts that have no numbered sections (Parts 26 to 28). */',
    '  topics: OutlineTopic[]',
    '  sections: OutlineSection[]',
    '}',
    '',
    `export const OUTLINE: OutlinePart[] = ${JSON.stringify(parts, null, 2)}`,
    '',
  ].join('\n')
}
