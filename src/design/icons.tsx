type Pillars = (typeof PILLARS)[number]
type RegistryIconName =
  | Pillars['icon']
  | Pillars['parts'][number]['icon']
  | (typeof EFFECT_CATEGORIES)[number]['icon']
  | (typeof INSTRUMENT_FAMILIES)[number]['icon']

